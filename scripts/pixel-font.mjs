const glyph = (ch) => (G[ch] ?? G[ch.toUpperCase()] ?? "").split(" ").filter(Boolean);

// Width in device pixels of `text` drawn with dots of size `dot`.
export function textWidth(text, dot) {
  const glyphs = [...text].map(glyph).filter((g) => g.length);
  return glyphs.reduce((w, g) => w + (g[0].length + 1) * dot, 0) - dot;
}

// SVG path data for `text`, top-left at (x, y).
export function textPath(text, x, y, dot) {
  let d = "";
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    if (!g.length) continue;
    g.forEach((row, r) => {
      let c = 0;
      while (c < row.length) {
        if (row[c] !== "1") { c++; continue; }
        let run = 1;
        while (row[c + run] === "1") run++;
        d += `M${cx + c * dot} ${y + r * dot}h${run * dot}v${dot}h${-run * dot}z`;
        c += run;
      }
    });
    cx += (g[0].length + 1) * dot;
  }
  return d;
}
